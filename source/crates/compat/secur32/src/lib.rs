pub struct PerfState {
    pub opened: bool,
    pub refs: u32,
    pub view: usize,
    pub section: usize,
}

pub static STATE: Mutex<PerfState> = Mutex::new(PerfState { opened: false, refs: 0, view: 0, section: 0 });

fn wide(s: &str) -> Vec<u16> {
    s.encode_utf16().chain(Some(0)).collect()
}

unsafe fn wstr_eq(a: *const u16, b: &str) -> bool {
    let mut i = 0;
    for c in b.encode_utf16() {
        if *a.add(i) != c {
            return false;
        }
        i += 1;
    }
    *a.add(i) == 0
}

pub unsafe fn query_type(value: *const u16) -> u32 {
    if value.is_null() || *value == 0 || wstr_eq(value, "Global") {
        return 1;
    }
    if wstr_eq(value, "Foreign") {
        return 3;
    }
    if wstr_eq(value, "Costly") {
        return 4;
    }
    2
}

pub unsafe fn is_number_in_list(number: u32, list: *const u16) -> bool {
    if list.is_null() {
        return false;
    }
    let mut p = list;
    loop {
        while *p != 0 && iswspace(*p) != 0 {
            p = p.add(1);
        }
        let mut digits = 0u32;
        let mut value = 0u32;
        while iswdigit(*p) != 0 {
            value = (*p as u32).wrapping_add(value.wrapping_mul(10)).wrapping_sub(0x30);
            p = p.add(1);
            digits += 1;
        }
        if digits == 0 {
            return false;
        }
        if value == number {
            return true;
        }
        if *p == 0 {
            return false;
        }
    }
}

pub unsafe fn processor_count() -> u32 {
    let peb: usize;
    core::arch::asm!("mov {}, gs:[0x60]", out(reg) peb, options(nostack, readonly, preserves_flags));
    (*((peb + 0xb8) as *const u32)).min(0x40)
}

#[no_mangle]
pub unsafe extern "system" fn OpenLsaPerformanceData(_device_names: *const u16) -> u32 {
    let mut st = STATE.lock().unwrap_or_else(|e| e.into_inner());
    if st.refs != 0 {
        st.refs += 1;
        return 0;
    }
    let name = wide("\\LsaPerformance");
    let us = UnicodeString { length: ((name.len() - 1) * 2) as u16, maximum_length: (name.len() * 2) as u16, buffer: name.as_ptr() };
    let oa = ObjectAttributes { length: 0x30, root: core::ptr::null_mut(), name: &us, attributes: 0, security_descriptor: core::ptr::null_mut(), security_qos: core::ptr::null_mut() };
    let mut section: *mut c_void = core::ptr::null_mut();
    let mut status = NtOpenSection(&mut section, SECTION_MAP_READ, &oa);
    st.section = section as usize;
    if status >= 0 {
        let mut base: *mut c_void = core::ptr::null_mut();
        let mut size = 0usize;
        status = NtMapViewOfSection(section, -1, &mut base, 0, 0, core::ptr::null_mut(), &mut size, VIEW_SHARE, 0, PAGE_READONLY);
        st.view = base as usize;
        if status >= 0 {
            st.opened = true;
            st.refs += 1;
            return 0;
        }
    }
    if st.view != 0 {
        NtUnmapViewOfSection(-1, st.view as *mut c_void);
        st.view = 0;
    }
    if st.section != 0 {
        NtClose(st.section as *mut c_void);
        st.section = 0;
    }
    RtlNtStatusToDosError(status)
}

#[no_mangle]
pub unsafe extern "system" fn CloseLsaPerformanceData() -> u32 {
    let mut st = STATE.lock().unwrap_or_else(|e| e.into_inner());
    if st.opened {
        st.refs = st.refs.wrapping_sub(1);
        if st.refs == 0 {
            NtUnmapViewOfSection(-1, st.view as *mut c_void);
            st.view = 0;
            NtClose(st.section as *mut c_void);
            st.section = 0;
        }
    }
    0
}

unsafe fn rd(view: usize, off: usize) -> u32 {
    if view == 0 {
        let args = [0usize, off];
        RaiseException(STATUS_ACCESS_VIOLATION, 0, 2, args.as_ptr());
    }
    core::ptr::read_unaligned((view + off) as *const u32)
}

unsafe fn wr(p: *mut u8, off: usize, v: u32) {
    core::ptr::write_unaligned(p.add(off) as *mut u32, v)
}

unsafe fn rdo(p: *const u8, off: usize) -> u32 {
    core::ptr::read_unaligned(p.add(off) as *const u32)
}

unsafe fn clear(total_bytes: *mut u32, num_objects: *mut u32, code: u32) -> u32 {
    *total_bytes = 0;
    *num_objects = 0;
    code
}

pub unsafe fn collect_from(view: usize, cpus: usize, value_name: *const u16, data: *mut *mut u8, total_bytes: *mut u32, num_objects: *mut u32) -> u32 {
    let qt = query_type(value_name);
    if qt.wrapping_sub(3) <= 1 {
        return clear(total_bytes, num_objects, 0);
    }
    let mut want_lsa = true;
    let mut want_inst = true;
    if qt == 2 {
        want_lsa = is_number_in_list(LSA_OBJECT_INDEX, value_name);
        want_inst = is_number_in_list(INSTANCE_OBJECT_INDEX, value_name);
        if !want_lsa && !want_inst {
            return clear(total_bytes, num_objects, 0);
        }
    }
    let mut out = *data;
    *num_objects = 0;
    let mut used: u32 = 0;
    if want_lsa {
        used = LSA_OBJECT_SIZE;
        if *total_bytes < used {
            return clear(total_bytes, num_objects, ERROR_MORE_DATA);
        }
        core::ptr::copy_nonoverlapping(LSA_OBJECT_TEMPLATE.as_ptr(), out, LSA_OBJECT_TEMPLATE.len());
        wr(out, 0x360, 0x58);
        core::ptr::write_bytes(out.add(0x368), 0, LSA_COUNTERS * 4);
        for cpu in 0..cpus {
            for i in 0..LSA_COUNTERS {
                let v = rdo(out, 0x368 + 4 * i).wrapping_add(rd(view, cpu * PER_CPU_STRIDE + 4 * i));
                wr(out, 0x368 + 4 * i, v);
            }
        }
        out = out.add(LSA_OBJECT_SIZE as usize);
        *num_objects += 1;
    }
    if want_inst {
        used += INSTANCE_OBJECT_SIZE;
        if *total_bytes < used {
            return clear(total_bytes, num_objects, ERROR_MORE_DATA);
        }
        core::ptr::copy_nonoverlapping(INSTANCE_OBJECT_TEMPLATE.as_ptr(), out, INSTANCE_OBJECT_TEMPLATE.len());
        let mut inst = out.add(INSTANCE_OBJECT_SIZE as usize);
        for i in 0..INSTANCE_ENTRIES {
            let entry = INSTANCE_BASE + INSTANCE_ENTRY * i;
            let id = rd(view, entry);
            if id == 0 {
                continue;
            }
            let mut name = [0u16; 16];
            _itow(id as i32, name.as_mut_ptr(), 10);
            let chars = name.iter().position(|&c| c == 0).unwrap_or(name.len());
            let name_bytes = (chars * 2 + 2) as u32;
            let padded = (name_bytes + 7) & !7;
            used += padded + 0x28;
            if *total_bytes < used {
                return clear(total_bytes, num_objects, ERROR_MORE_DATA);
            }
            core::ptr::write_bytes(inst, 0, (padded + 0x28) as usize);
            wr(inst, 0, padded + 0x18);
            wr(inst, 0xc, 0xffff_ffff);
            wr(inst, 0x10, 0x18);
            wr(inst, 0x14, name_bytes);
            core::ptr::copy_nonoverlapping(name.as_ptr() as *const u8, inst.add(0x18), name_bytes as usize);
            let block = inst.add(padded as usize);
            wr(block, 0x18, 0x10);
            for cpu in 0..cpus {
                let a = rdo(block, 0x1c).wrapping_add(rd(view, cpu * PER_CPU_STRIDE + entry + 4));
                wr(block, 0x1c, a);
                let b = rdo(block, 0x20).wrapping_add(rd(view, cpu * PER_CPU_STRIDE + entry + 8));
                wr(block, 0x20, b);
            }
            wr(out, 0x28, rdo(out, 0x28).wrapping_add(1));
            wr(out, 0, rdo(out, 0).wrapping_add(padded + 0x28));
            inst = block.add(0x28);
        }
        *num_objects += 1;
    }
    *data = (*data).add(used as usize);
    *total_bytes = used;
    0
}

#[no_mangle]
pub unsafe extern "system" fn CollectLsaPerformanceData(value_name: *const u16, data: *mut *mut u8, total_bytes: *mut u32, num_objects: *mut u32) -> u32 {
    let st = STATE.lock().unwrap_or_else(|e| e.into_inner());
    if !st.opened {
        *total_bytes = 0;
        *num_objects = 0;
        return 0;
    }
    let view = st.view;
    drop(st);
    collect_from(view, processor_count() as usize, value_name, data, total_bytes, num_objects)
}

