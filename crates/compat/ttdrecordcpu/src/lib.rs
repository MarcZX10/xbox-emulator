#[repr(C)]
#[derive(Clone, Copy, Default, Debug, PartialEq, Eq)]
pub struct Pair {
    pub a: u64,
    pub b: u64,
}

unsafe extern "system" fn default_noop() {}

unsafe extern "system" fn default_zero_pair(out: *mut Pair) -> *mut Pair {
    unsafe { out.write(Pair::default()) };
    out
}

pub fn default_callback(slot: usize) -> usize {
    if slot == STRUCT_DEFAULT_SLOT {
        default_zero_pair as *const () as usize
    } else {
        default_noop as *const () as usize
    }
}

static CALLBACKS: [AtomicUsize; CALLBACK_SLOTS] = [const { AtomicUsize::new(0) }; CALLBACK_SLOTS];

pub fn instrumentation_callback(slot: usize) -> usize {
    CALLBACKS[slot].load(Ordering::SeqCst)
}

#[no_mangle]
pub extern "system" fn GetRegisterOffsets(arch: u8) -> *const u16 {
    if arch == ARCH_X64 {
        TTD_X64_REGISTER_OFFSETS.as_ptr()
    } else {
        core::ptr::null()
    }
}

#[no_mangle]
pub unsafe extern "system" fn RegisterInstrumentationCallbacks(table: *const usize) {
    for slot in 0..CALLBACK_SLOTS {
        let v = unsafe { table.add(slot).read() };
        CALLBACKS[slot].store(if v == 0 { default_callback(slot) } else { v }, Ordering::SeqCst);
    }
}

